#!/usr/bin/env python3
"""One-shot migration: split the translation blob out of i18n.js into i18n/<code>.js.

Before this, every visitor downloaded all 17 translation tables (359 KB raw) to
read one. The runtime keeps the language list, the English templates and the
loader; each language becomes its own file, fetched the first time it is
selected.

Idempotent guard: it refuses to run once the blob is gone.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
I18N = os.path.join(ROOT, "i18n.js")
OUT_DIR = os.path.join(ROOT, "i18n")

HEADER = """/* Parent Advisor i18n: {code} ({native}).
   Generated by tools/split_i18n.py. Loaded on demand by the i18n runtime when
   this language is selected; English is the source text and has no file. */
"""


def main() -> int:
    src = open(I18N, encoding="utf-8").read()
    marker = "window.PAi18n.data("
    if marker not in src:
        print("i18n.js has no data blob: already split, nothing to do")
        return 0

    start = src.index(marker) + len(marker)
    data, _ = json.JSONDecoder().raw_decode(src[start:])

    # read the LANGS table out of the runtime for the native names
    langs = {}
    for code, native in re.findall(r"\{ code: '([a-z]{2})',.*?native: '((?:[^'\\]|\\.)*)'", src):
        langs[code] = native

    os.makedirs(OUT_DIR, exist_ok=True)
    total = 0
    for code in sorted(data):
        native = langs.get(code, code)
        body = json.dumps({code: data[code]}, ensure_ascii=False, separators=(",", ":"))
        path = os.path.join(OUT_DIR, code + ".js")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(HEADER.format(code=code, native=native))
            fh.write("window.PAi18n.data(" + body + ");\n")
        total += os.path.getsize(path)
        print("%-4s %7.1f KB  %s" % (code, os.path.getsize(path) / 1024, os.path.relpath(path, ROOT)))

    # cut the blob and the generated-footer comment off i18n.js
    end = src.index("});", start) + 3
    head = src[:src.index(marker)].rstrip()
    tail = src[end:]
    # drop the "/* generated: ... bytes */" trailer
    tail = re.sub(r"\n*/\* generated:[^*]*\*/", "", tail)
    with open(I18N, "w", encoding="utf-8") as fh:
        fh.write(head + "\n" + tail.strip() + "\n")

    print("\n%d language files, %.1f KB total" % (len(data), total / 1024))
    print("i18n.js is now %.1f KB" % (os.path.getsize(I18N) / 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main())